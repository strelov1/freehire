// Command gen-contracts regenerates web/src/lib/generated/contracts.ts from the Go
// contracts: the Job/Enrichment wire structs (via tygo) and the closed vocabularies
// (source/stages/enrichment facet values). Run it with `make gen-contracts` (a separate module in tools/); the
// output is committed, so the build never depends on this tool.
package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/gzuidhof/tygo/tygo"
)

const outputPath = "../web/src/lib/generated/contracts.ts"

const header = "// Code generated by tools/gen-contracts. DO NOT EDIT.\n" +
	"// Regenerate with `make gen-contracts`.\n\n"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-contracts:", err)
		os.Exit(1)
	}
}

func run() error {
	structs, err := genStructs()
	if err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString(structs)
	b.WriteString("\n")
	b.WriteString(genVocab())

	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(outputPath, []byte(b.String()), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(skillDescriptionsPath, []byte(genSkillDescriptions()), 0o644); err != nil {
		return err
	}
	return os.WriteFile(skillAliasesPath, []byte(genSkillAliases()), 0o644)
}

