package main

import (
	"errors"
	"os"
	"path/filepath"
	"testing"
)

const sample = `// Code generated by internal/dict/skillvec/gen. DO NOT EDIT BY HAND.

package skillvec

var registry = []string{
	"go",
	"docker",
	"kubernetes",
}
`

func TestReadAssignedPreservesOrder(t *testing.T) {
	path := filepath.Join(t.TempDir(), "registry.go")
	if err := os.WriteFile(path, []byte(sample), 0o644); err != nil {
		t.Fatal(err)
	}
	got, err := readAssigned(path)
	if err != nil {
		t.Fatalf("readAssigned: %v", err)
	}
	want := []string{"go", "docker", "kubernetes"}
	if len(got) != len(want) {
		t.Fatalf("read %d entries, want %d: %v", len(got), len(want), got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("position %d = %q, want %q — order IS the position", i, got[i], want[i])
		}
	}
}

func TestReadAssignedTreatsAMissingFileAsTheFirstRun(t *testing.T) {
	got, err := readAssigned(filepath.Join(t.TempDir(), "absent.go"))
	if err != nil {
		t.Fatalf("a missing registry is the first run, not an error: %v", err)
	}
	if len(got) != 0 {
		t.Errorf("read %v from a missing file, want nothing", got)
	}
}

// The dangerous case. Any read error other than "not there" must abort: treating an
// unreadable-but-writable registry as a first run would rewrite every position in
// canonical order, silently invalidating every vector already in the search index.
func TestReadAssignedRefusesAnUnreadableRegistry(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("running as root: permission bits do not deny reads")
	}
	path := filepath.Join(t.TempDir(), "registry.go")
	if err := os.WriteFile(path, []byte(sample), 0o000); err != nil {
		t.Fatal(err)
	}
	if _, err := readAssigned(path); err == nil {
		t.Error("an unreadable registry was treated as a first run")
	} else if errors.Is(err, os.ErrNotExist) {
		t.Errorf("error = %v, want a permission error rather than not-exist", err)
	}
}

// A file that exists but parses to nothing is corruption, not a first run: rewriting
// it from scratch would reassign every position.
func TestReadAssignedRefusesAPresentButEmptyRegistry(t *testing.T) {
	path := filepath.Join(t.TempDir(), "registry.go")
	if err := os.WriteFile(path, []byte("package skillvec\n\nvar registry = []string{\n}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := readAssigned(path); err == nil {
		t.Error("a present registry holding no positions was accepted; that would reassign every position")
	}
}
