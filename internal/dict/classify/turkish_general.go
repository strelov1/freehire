// 24,956 postings of its whole catalogue resolved a category for only 6.7% of their titles, the
// English dictionary reading a Turkish retail, accounting or production title as nothing. This
// table is read after the IT table (turkish.go) and follows the same rules: stems on the folded
// title, an alias opening with "^" must start the title, and every answer is the one the English
// twin of the title gets — a "Satış Danışmanı" is a Sales Consultant, a "Muhasebe Elemanı" an
