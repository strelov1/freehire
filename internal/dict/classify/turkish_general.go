//
// Where the English twin resolves nothing the title stays unresolved too, unless the field is
// unmistakable: "Kalite Kontrol Uzmanı" is filed with the quality engineers because
// industrial_engineering is defined as the seat that makes and runs the thing, quality included.
// Generic heads (Uzman, Danışman, Sorumlu, Yönetici, Müdür, Eleman, Personel, Görevli) carry no
// category of their own: the field word before them does, as in Spanish (spanish.go).
