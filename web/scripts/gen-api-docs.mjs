// Generates docs/API.md and docs/API.internal.md from the single typed source
// web/src/lib/docs/api-spec.ts (+ filters.ts), so the repo Markdown and the
// /docs/api and /docs/api/internal pages never drift. partitionForAudience splits
// the one spec into the two documents by each endpoint's `auth` level — see its
// own comment for the external/internal boundary.
//
// Like scripts/og-smoke.mjs, it loads the TypeScript source through Vite's SSR
// loader (Vite is already a devDependency) — no .ts-extension imports, no new
// tooling. renderMarkdown is a PURE function (data in, string out) so the smoke
// (scripts/gen-api-docs-smoke.mjs) can assert its output without touching disk.
//
//   node scripts/gen-api-docs.mjs    # writes ../docs/API.md and ../docs/API.internal.md

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createServer } from 'vite';
import { renderFilterSectionLines } from './renderFilterSection.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const outFile = resolve(webRoot, '..', 'docs', 'API.md');
const outFileInternal = resolve(webRoot, '..', 'docs', 'API.internal.md');

const GENERATED_HEADER =
  '<!-- GENERATED by web/scripts/gen-api-docs.mjs from web/src/lib/docs/api-spec.ts. ' +
  'Do not edit by hand — run `pnpm run gen:api-docs`. -->';

// The anchor a Markdown renderer derives from a heading, so the table of contents
// links land. This is GitHub's rule, not one of our own: lowercase, DROP anything that
// is not a letter, digit, space or hyphen, then turn spaces into hyphens.
//
// The dropping matters and is why this is not `[^a-z0-9]+ -> '-'`. That collapsed a RUN
// of punctuation-and-space into ONE hyphen, so "Account, plan & extension" produced
// `account-plan-extension` while every renderer produced `account-plan--extension` —
// the `&` vanishes and leaves the two spaces around it behind. Ten headings in the
// generated document carry an `&`, and every one of their TOC links was dead.
function slug(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .replace(/ /g, '-');
}

// Markdown table from a header row and string cells. Empty rows array yields "".
function table(headers, rows) {
  if (rows.length === 0) return '';
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.join(' | ')} |`).join('\n');
  return `${head}\n${sep}\n${body}`;
}

function paramRows(params) {
  return params.map((p) => [
    `\`${p.name}\``,
    p.type,
    p.required ? 'yes' : 'no',
    p.example ? `${p.description} (e.g. \`${p.example}\`)` : p.description,
  ]);
}

function renderEndpoint(ep, auths) {
  const out = [];
  out.push(`### \`${ep.method} ${ep.path}\``);
  out.push('');
  out.push(`**Auth:** ${auths[ep.auth]}`);
  if (ep.deprecated) {
    out.push('');
    out.push(`**Deprecated** since ${ep.deprecated.since} — use \`${ep.deprecated.replacement}\` instead.`);
  }
  out.push('');
  out.push(ep.summary);
  if (ep.description) {
    out.push('');
    out.push(ep.description);
  }
  if (ep.pathParams?.length) {
    out.push('');
    out.push('**Path parameters**');
    out.push('');
    out.push(table(['Name', 'Type', 'Required', 'Description'], paramRows(ep.pathParams)));
  }
  if (ep.query?.length) {
    out.push('');
    out.push('**Query parameters**');
    out.push('');
    out.push(table(['Name', 'Type', 'Required', 'Description'], paramRows(ep.query)));
  }
  if (ep.filterable) {
    out.push('');
    out.push('Plus every filter in [Filtering jobs](#filtering-jobs).');
  }
  if (ep.body?.length) {
    out.push('');
    out.push('**Body**');
    out.push('');
    out.push(table(['Name', 'Type', 'Required', 'Description'], paramRows(ep.body)));
  }
  out.push('');
  out.push('```bash');
  out.push(ep.curl);
  out.push('```');
  if (ep.responseExample) {
    out.push('');
    out.push('```json');
    out.push(ep.responseExample);
    out.push('```');
  }
  return out.join('\n');
}

// The internal document's title, shared by both generators' `main()` (and by
// gen-openapi.mjs's import of it) so the two never drift apart.
export const INTERNAL_TITLE = 'freehire API — internal reference';

// Which `Endpoint.auth` levels a caller outside the browser can reach. 'none' and
// 'cookie-or-key' both accept a personal API key (or need no auth at all), so an agent
// or script can call them; 'cookie', 'moderator' and 'extension' accept only the
// browser's own session cookie, so nothing outside a signed-in browser tab can ever
// call them, no matter what credential it holds.
const AUDIENCE_AUTH = {
  external: new Set(['none', 'cookie-or-key']),
  internal: new Set(['cookie', 'moderator', 'extension']),
};

// The one section that differs between the two documents — everything else in
// OVERVIEW is shared verbatim. Inserted right after "Authentication model", the
// section it most directly continues.
const AUDIENCE_INTRO = {
  external: {
    title: 'External vs internal endpoints',
    paragraphs: [
      'This reference covers every endpoint a client can call from outside the ' +
        'browser: public reads, and endpoints that also accept a personal API key. ' +
        'Endpoints that require the browser’s own session cookie — saved ' +
        'searches, notifications, moderator tools, the browser extension — are ' +
        'not reachable with a key alone and are documented separately at ' +
        '[freehire.me/docs/api/internal](https://freehire.me/docs/api/internal).',
    ],
  },
  internal: {
    title: 'External vs internal endpoints',
    paragraphs: [
      'This reference covers endpoints that require the browser’s own session ' +
        'cookie — including moderator-only and browser-extension-only endpoints. ' +
        'None of them accept a personal API key, so an external client or agent ' +
        'cannot call them. For the endpoints a key (or no auth at all) can reach, ' +
        'see [freehire.me/docs/api](https://freehire.me/docs/api).',
    ],
  },
};

// AUDIENCE_AUTH is a plain runtime Set, with no compiler tie to api-spec.ts's
// `Auth` union — unlike AUTH_LABELS there, a `Record<Auth, string>` TypeScript
// already forces to be exhaustive. Checked against AUTH_LABELS' own keys (the
// spec's one exhaustive enumeration of `Auth`) so a future auth level that
// AUDIENCE_AUTH doesn't route anywhere fails loudly here, instead of silently
// vanishing from both documents via `allow.has(ep.auth)` being false in both.
function assertAudienceAuthIsExhaustive(authLabels) {
  const covered = new Set([...AUDIENCE_AUTH.external, ...AUDIENCE_AUTH.internal]);
  const uncovered = Object.keys(authLabels).filter((auth) => !covered.has(auth));
  if (uncovered.length > 0) {
    throw new Error(
      `AUDIENCE_AUTH does not route auth level(s) ${uncovered.join(', ')} to either audience — add them to AUDIENCE_AUTH in gen-api-docs.mjs`,
    );
  }
}

// Pure: (spec, audience) -> a new spec restricted to that audience's endpoints, with
// the matching intro section spliced into OVERVIEW. A group left with no endpoints for
// this audience (e.g. "Moderator jobs" for 'external') is dropped rather than rendered
// empty.
export function partitionForAudience(spec, audience) {
  const allow = AUDIENCE_AUTH[audience];
  if (!allow) throw new Error(`Unknown audience "${audience}" — add it to AUDIENCE_AUTH in gen-api-docs.mjs`);
  assertAudienceAuthIsExhaustive(spec.AUTH_LABELS);

  const GROUPS = spec.GROUPS.map((g) => ({
    ...g,
    endpoints: g.endpoints.filter((ep) => allow.has(ep.auth)),
  })).filter((g) => g.endpoints.length > 0);

  const authIndex = spec.OVERVIEW.findIndex((o) => o.title === 'Authentication model');
  if (authIndex === -1) throw new Error('OVERVIEW has no "Authentication model" section to splice the audience intro after');
  const OVERVIEW = [...spec.OVERVIEW];
  OVERVIEW.splice(authIndex + 1, 0, AUDIENCE_INTRO[audience]);

  return { ...spec, GROUPS, OVERVIEW };
}

// Pure: (spec, filters, opts?) -> Markdown string. Deterministic, no IO.
export function renderMarkdown(spec, filters, { title = 'freehire API' } = {}) {
  const { BASE_URL, OVERVIEW, GROUPS, AUTH_LABELS } = spec;
  const out = [];
  out.push(GENERATED_HEADER);
  out.push('');
  out.push(`# ${title}`);
  out.push('');
  out.push(`Base URL: \`${BASE_URL}\``);
  out.push('');

  // Table of contents.
  out.push('## Contents');
  out.push('');
  for (const o of OVERVIEW) out.push(`- [${o.title}](#${slug(o.title)})`);
  out.push('- [Filtering jobs](#filtering-jobs)');
  for (const g of GROUPS) out.push(`- [${g.title}](#${slug(g.title)})`);
  out.push('');

  // Overview sections.
  for (const o of OVERVIEW) {
    out.push(`## ${o.title}`);
    out.push('');
    for (const p of o.paragraphs) {
      out.push(p);
      out.push('');
    }
    if (o.code) {
      out.push('```json');
      out.push(o.code);
      out.push('```');
      out.push('');
    }
  }

  // Filters.
  out.push(...renderFilterSectionLines(filters));
  out.push('');

  // Endpoint groups.
  for (const g of GROUPS) {
    out.push(`## ${g.title}`);
    out.push('');
    out.push(g.intro);
    out.push('');
    for (const ep of g.endpoints) {
      out.push(renderEndpoint(ep, AUTH_LABELS));
      out.push('');
    }
  }

  return `${out.join('\n').trimEnd()}\n`;
}

// Loads the spec + filters modules through Vite's SSR loader.
export async function loadDocsModules() {
  const vite = await createServer({
    configFile: false,
    root: webRoot,
    logLevel: 'error',
  });
  try {
    const spec = await vite.ssrLoadModule('/src/lib/docs/api-spec.ts');
    const filters = await vite.ssrLoadModule('/src/lib/docs/filters.ts');
    return { spec, filters };
  } finally {
    await vite.close();
  }
}

async function main() {
  const { spec, filters } = await loadDocsModules();

  const md = renderMarkdown(partitionForAudience(spec, 'external'), filters);
  await writeFile(outFile, md);
  console.log(`Wrote ${outFile} (${md.length} bytes)`);

  const mdInternal = renderMarkdown(partitionForAudience(spec, 'internal'), filters, { title: INTERNAL_TITLE });
  await writeFile(outFileInternal, mdInternal);
  console.log(`Wrote ${outFileInternal} (${mdInternal.length} bytes)`);
}

// Run only when invoked directly, so the smoke can import renderMarkdown/loadDocsModules.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
