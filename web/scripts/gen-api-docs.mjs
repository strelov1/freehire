// Generates the API reference from the HTTP contract: openapi/api.openapi.json (compiled from
// typespec/ by `make api-contract`) plus web/src/lib/docs/api-supplement.openapi.json, the
// hand-written routes the contract does not describe yet (auth, SSE streams, binary reads).
// Writes four files, two per audience:
//
//   src/lib/docs/generated/api-reference.openapi.json            the /docs/api Scalar page
//   src/lib/docs/generated/api-reference.internal.openapi.json   the /docs/api/internal page
//   ../docs/API.md, ../docs/API.internal.md                       the same, as Markdown
//
// The audience comes from the contract. An operation an API key (or nobody) can call is
// external; one that needs the browser's session cookie is internal. `x-audience` overrides
// that: `moderator` and `extension` are internal whatever the credential, `hidden` is in
// neither document.
//
// The job-search filter section is the one part not in the contract: it is derived from
// src/lib/docs/filters.ts (loaded through Vite, like og-smoke.mjs does), so it stays in step
// with the facet vocabulary the SPA uses.
//
//   node scripts/gen-api-docs.mjs

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createServer } from 'vite';
import { renderFilterSectionLines } from './renderFilterSection.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const contractFile = resolve(webRoot, '..', 'openapi', 'api.openapi.json');
const supplementFile = resolve(webRoot, 'src', 'lib', 'docs', 'api-supplement.openapi.json');
const generatedDir = resolve(webRoot, 'src', 'lib', 'docs', 'generated');

const OUTPUTS = {
  external: {
    openapi: resolve(generatedDir, 'api-reference.openapi.json'),
    markdown: resolve(webRoot, '..', 'docs', 'API.md'),
    title: 'freehire API',
  },
  internal: {
    openapi: resolve(generatedDir, 'api-reference.internal.openapi.json'),
    markdown: resolve(webRoot, '..', 'docs', 'API.internal.md'),
    title: 'freehire API — internal reference',
  },
};

const GENERATED_HEADER =
  '<!-- GENERATED by web/scripts/gen-api-docs.mjs from openapi/api.openapi.json (typespec/). ' +
  'Do not edit by hand — run `make api-contract`, then `pnpm run gen:api-docs` in web/. -->';

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

// The section that differs between the two documents, after the contract's own overview.
const AUDIENCE_INTRO = {
  external:
    'This reference covers every endpoint a client can call from outside the browser: public ' +
    'reads, and endpoints that also accept a personal API key. Endpoints that require the ' +
    'browser’s own session cookie — saved searches, notifications, moderator tools, the browser ' +
    'extension — are not reachable with a key alone and are documented separately at ' +
    '[freehire.me/docs/api/internal](https://freehire.me/docs/api/internal).',
  internal:
    'This reference covers endpoints that require the browser’s own session cookie — including ' +
    'moderator-only and browser-extension-only endpoints. None of them accept a personal API ' +
    'key, so an external client or agent cannot call them. For the endpoints a key (or no auth ' +
    'at all) can reach, see [freehire.me/docs/api](https://freehire.me/docs/api).',
};

// Folds the supplement into the contract. A route in both means it moved into the contract,
// and its hand-written entry is now a second, drifting description of it.
export function mergeSupplement(contract, supplement) {
  const paths = structuredClone(contract.paths);
  for (const [path, item] of Object.entries(supplement.paths)) {
    for (const [method, op] of Object.entries(item)) {
      if (paths[path]?.[method]) {
        throw new Error(
          `${method.toUpperCase()} ${path} is in the contract now — delete it from api-supplement.openapi.json`,
        );
      }
      (paths[path] ??= {})[method] = op;
    }
  }
  return { ...contract, paths };
}

const ACCESS_LABELS = {
  public: 'Public',
  key: 'Session or API key',
  cookie: 'Session only',
  moderator: 'Moderator',
  extension: 'Browser extension only',
  hidden: 'Not documented',
};

// 'public' | 'key' | 'cookie' | 'moderator' | 'extension' | 'hidden', from the op's security
// and x-audience.
export function accessOf(op, doc) {
  const audience = op['x-audience'];
  if (audience) {
    if (!(audience in ACCESS_LABELS)) throw new Error(`unknown x-audience "${audience}"`);
    return audience;
  }
  const security = op.security ?? doc.security ?? [];
  if (security.length === 0 || security.some((s) => Object.keys(s).length === 0)) return 'public';
  return security.some((s) => 'PersonalApiKey' in s) ? 'key' : 'cookie';
}

function audienceOf(access) {
  if (access === 'hidden') return null;
  return access === 'public' || access === 'key' ? 'external' : 'internal';
}

// Every component schema an object reaches through $ref, transitively. Shared parameters
// are kept whole (a handful), so their schemas count as reached.
function reachableSchemas(root, schemas) {
  const seen = new Set();
  const walk = (node) => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (!node || typeof node !== 'object') return;
    const ref = node.$ref?.match(/^#\/components\/schemas\/(.+)$/)?.[1];
    if (ref && !seen.has(ref)) {
      seen.add(ref);
      walk(schemas[ref]);
    }
    Object.values(node).forEach(walk);
  };
  walk(root);
  return seen;
}

// Pure: (merged contract, filters module, audience) -> the audience's OpenAPI document.
export function renderOpenApi(doc, filters, audience) {
  const paths = {};
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op || audienceOf(accessOf(op, doc)) !== audience) continue;
      (paths[path] ??= {})[method] = op;
    }
  }
  const used = new Set(Object.values(paths).flatMap((item) => Object.values(item).flatMap((op) => op.tags ?? [])));
  const listed = new Set((doc.tags ?? []).map((t) => t.name));
  const tags = [
    ...(doc.tags ?? []).filter((t) => used.has(t.name)),
    ...[...used]
      .filter((name) => !listed.has(name))
      .sort()
      .map((name) => ({ name })),
  ];
  const keep = reachableSchemas([paths, doc.components.parameters], doc.components.schemas);
  const schemas = Object.fromEntries(Object.entries(doc.components.schemas).filter(([name]) => keep.has(name)));
  const description = [
    doc.info.description,
    '## External vs internal endpoints',
    AUDIENCE_INTRO[audience],
    ...renderFilterSectionLines(filters),
  ].join('\n\n');
  return {
    openapi: doc.openapi,
    info: { title: OUTPUTS[audience].title, description, version: '1.0.0' },
    servers: doc.servers,
    security: doc.security,
    tags,
    paths,
    components: { ...doc.components, schemas },
  };
}

// The anchor a Markdown renderer derives from a heading (GitHub's rule): lowercase, drop
// anything not a letter, digit, space or hyphen, then spaces to hyphens. Dropping, not
// collapsing, is what keeps "A & B" at `a--b`, the anchor every renderer produces.
function slug(s) {
  return s
    .toLowerCase()
    .replace(/[^\p{L}\p{N} -]/gu, '')
    .replace(/ /g, '-');
}

function table(headers, rows) {
  if (rows.length === 0) return [];
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ];
}

const cell = (s) => (s ?? '').replace(/\s*\n\s*/g, ' ').replace(/[\\|]/g, '\\$&');

// A schema or parameter `$ref` into the document's components, or the object itself.
function resolveRef(node, doc) {
  const [, section, name] = node?.$ref?.match(/^#\/components\/(\w+)\/(.+)$/) ?? [];
  return name ? doc.components[section][name] : node;
}

function typeName(schema) {
  if (!schema) return 'any';
  const ref = schema.$ref?.match(/([^/]+)$/)?.[1];
  if (ref) return ref;
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map((s) => typeName(s)).join(' \\| ');
  if (schema.type === 'array') return `${typeName(schema.items)}[]`;
  if (Array.isArray(schema.type)) return schema.type.join(' \\| ');
  return schema.format ? `${schema.type} (${schema.format})` : (schema.type ?? 'any');
}

function exampleOf(content) {
  if (!content) return undefined;
  const [type, media] = Object.entries(content)[0];
  const example = media.example ?? Object.values(media.examples ?? {})[0]?.value;
  return example === undefined ? undefined : { type, example };
}

function curlFor(method, path, op, access, base) {
  const parts = ['curl'];
  if (method !== 'get') parts.push(`-X ${method.toUpperCase()}`);
  parts.push(`"${base}${path.replace(/\{(\w+)\}/g, '<$1>')}"`);
  if (access === 'key') parts.push('-H "Authorization: Bearer $FREEHIRE_API_KEY"');
  if (access === 'cookie' || access === 'moderator') parts.push('-b cookies.txt');
  const body = exampleOf(op.requestBody?.content);
  if (body?.type === 'application/json') {
    parts.push(`-H 'Content-Type: application/json' -d '${JSON.stringify(body.example)}'`);
  }
  return parts.join(' ');
}

function renderOperation(method, path, op, doc) {
  const access = accessOf(op, doc);
  const out = [`### \`${method.toUpperCase()} ${path}\``, '', `**Auth:** ${ACCESS_LABELS[access]}`];
  if (op.deprecated) out.push('', '**Deprecated.**');
  if (op.summary) out.push('', op.summary);
  if (op.description) out.push('', op.description);
  for (const where of ['path', 'query']) {
    const params = (op.parameters ?? []).map((p) => resolveRef(p, doc)).filter((p) => p.in === where);
    if (!params.length) continue;
    out.push('', where === 'path' ? '**Path parameters**' : '**Query parameters**', '');
    out.push(
      ...table(
        ['Name', 'Type', 'Required', 'Description'],
        params.map((p) => [`\`${p.name}\``, typeName(p.schema), p.required ? 'yes' : 'no', cell(p.description)]),
      ),
    );
  }
  const media = op.requestBody && Object.values(op.requestBody.content)[0];
  const body = media && resolveRef(media.schema, doc);
  if (body?.properties) {
    const required = new Set(body.required ?? []);
    out.push('', '**Body**', '');
    out.push(
      ...table(
        ['Name', 'Type', 'Required', 'Description'],
        Object.entries(body.properties).map(([name, s]) => [
          `\`${name}\``,
          typeName(s),
          required.has(name) ? 'yes' : 'no',
          cell(s.description),
        ]),
      ),
    );
  }
  out.push('', '```bash', curlFor(method, path, op, access, doc.servers[0].url), '```');
  const ok = Object.entries(op.responses ?? {}).find(([status]) => status.startsWith('2'));
  const response = exampleOf(ok?.[1].content);
  if (response) {
    const json = response.type === 'application/json';
    out.push(
      '',
      json ? '```json' : '```',
      json ? JSON.stringify(response.example, null, 2) : String(response.example),
      '```',
    );
  }
  return out;
}

// Pure: (an audience's OpenAPI document) -> its Markdown. Deterministic, no IO.
export function renderMarkdown(doc) {
  const byTag = new Map(doc.tags.map((t) => [t.name, []]));
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of METHODS)
      if (item[method]) byTag.get((item[method].tags ?? [])[0])?.push([method, path, item[method]]);
  }
  const sections = doc.info.description.match(/^## .+$/gm).map((h) => h.slice(3));
  const out = [
    GENERATED_HEADER,
    '',
    `# ${doc.info.title}`,
    '',
    `Base URL: \`${doc.servers[0].url}\``,
    '',
    '## Contents',
    '',
  ];
  for (const s of sections) out.push(`- [${s}](#${slug(s)})`);
  for (const t of doc.tags) out.push(`- [${t.name}](#${slug(t.name)})`);
  out.push('', doc.info.description, '');
  for (const t of doc.tags) {
    out.push(`## ${t.name}`, '');
    if (t.description) out.push(t.description, '');
    for (const [method, path, op] of byTag.get(t.name)) out.push(...renderOperation(method, path, op, doc), '');
  }
  return `${out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`;
}

export async function loadSources() {
  const vite = await createServer({ configFile: false, root: webRoot, logLevel: 'error' });
  try {
    const filters = await vite.ssrLoadModule('/src/lib/docs/filters.ts');
    const contract = JSON.parse(await readFile(contractFile, 'utf8'));
    const supplement = JSON.parse(await readFile(supplementFile, 'utf8'));
    return { doc: mergeSupplement(contract, supplement), filters };
  } finally {
    await vite.close();
  }
}

async function main() {
  const { doc, filters } = await loadSources();
  await mkdir(generatedDir, { recursive: true });
  for (const [audience, out] of Object.entries(OUTPUTS)) {
    const openapi = renderOpenApi(doc, filters, audience);
    await writeFile(out.openapi, `${JSON.stringify(openapi, null, 2)}\n`);
    await writeFile(out.markdown, renderMarkdown(openapi));
    const count = Object.values(openapi.paths).reduce((n, item) => n + Object.keys(item).length, 0);
    console.log(`${audience}: ${count} operations -> ${out.openapi}, ${out.markdown}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
