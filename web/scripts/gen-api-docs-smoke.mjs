// Automated check for the API-docs generator (the project runs no JS unit runner over
// scripts/): the audience split, the supplement merge, and that the rendered documents carry
// what a reader needs.
//
//   node scripts/gen-api-docs-smoke.mjs   # asserts; exits non-zero on failure

import { accessOf, loadSources, mergeSupplement, renderMarkdown, renderOpenApi } from './gen-api-docs.mjs';
import { renderChatGptSchema } from './chatgptSchema.mjs';

const checks = [];
function assert(name, cond) {
  checks.push({ name, ok: Boolean(cond) });
}
const throws = (fn) => {
  try {
    fn();
    return false;
  } catch {
    return true;
  }
};

async function main() {
  const { doc, filters } = await loadSources();
  const extDoc = renderOpenApi(doc, filters, 'external');
  const intDoc = renderOpenApi(doc, filters, 'internal');
  const external = renderMarkdown(extDoc);
  const internal = renderMarkdown(intDoc);

  assert(
    'idempotent (two renders byte-identical)',
    external === renderMarkdown(renderOpenApi(doc, filters, 'external')),
  );
  assert('has generated header', external.startsWith('<!-- GENERATED by web/scripts/gen-api-docs.mjs'));
  assert('ends with single newline', external.endsWith('\n') && !external.endsWith('\n\n'));
  assert('has base URL', /^Base URL: `https:\/\/freehire\.me\/api\/v1`$/m.test(external));

  // The filter vocabulary comes from filters.ts, not the contract.
  assert('has filtering section', external.includes('## Filtering jobs'));
  assert('has a string facet (seniority)', external.includes('`seniority`'));
  assert('has the exclude modifier', external.includes('_exclude'));
  assert('has the first recipe query', external.includes(filters.RECIPES[0].query));

  // Audience: GET /jobs is public, POST /jobs is moderator-only — one path, both sides.
  assert('external documents GET /jobs', external.includes('### `GET /jobs`'));
  assert('external omits the moderator POST /jobs', !external.includes('### `POST /jobs`'));
  assert('internal documents the moderator POST /jobs', internal.includes('### `POST /jobs`'));
  assert('internal omits GET /jobs', !internal.includes('### `GET /jobs`'));
  assert('a key-accepting route is external', extDoc.paths['/me/tracking']?.get);
  assert('a cookie-only route is internal', intDoc.paths['/me/searches']?.get && !extDoc.paths['/me/searches']);
  assert('key routes show the Bearer header', external.includes('Authorization: Bearer $FREEHIRE_API_KEY'));
  assert('cross-links to the internal reference', external.includes('freehire.me/docs/api/internal'));
  assert('internal cross-links back', internal.includes('(https://freehire.me/docs/api)'));

  // Key management cannot be called by a client (cookie + fresh identity proof).
  assert('key management is in neither document', !(external + internal).includes('`GET /me/api-keys`'));
  assert('sends the reader to the account surface', external.includes('freehire.me/my/integrations/api-keys'));

  // A shared parameter ($ref into components.parameters) is listed like an inline one.
  assert('lists a shared talent filter param', /### `GET \/talent`[\s\S]*?\| `min_years` \|/.test(external));
  assert('extension-only routes are internal', internal.includes('**Auth:** Browser extension only'));

  // The supplement: routes outside the contract are still documented.
  assert('documents a supplement route (login)', external.includes('### `POST /auth/login`'));
  assert(
    'a supplement route already in the contract throws',
    throws(() => mergeSupplement(doc, { paths: { '/jobs': { get: {} } } })),
  );

  // Access rules.
  assert('public: empty requirement', accessOf({ security: [{}] }, doc) === 'public');
  assert(
    'key: any requirement names the key',
    accessOf({ security: [{ CookieSession: [] }, { PersonalApiKey: [] }] }, doc) === 'key',
  );
  assert('cookie: the namespace default', accessOf({}, doc) === 'cookie');
  assert(
    'moderator wins over the credential',
    accessOf({ security: [{}], 'x-audience': 'moderator' }, doc) === 'moderator',
  );

  // Every $ref in a document resolves inside it, after unused schemas were dropped.
  for (const [name, d] of [
    ['external', extDoc],
    ['internal', intDoc],
  ]) {
    const refs = JSON.stringify(d.paths).match(/#\/components\/schemas\/[^"]+/g) ?? [];
    assert(
      `${name}: every schema ref resolves`,
      refs.every((r) => d.components.schemas[r.split('/').pop()]),
    );
  }

  // The ChatGPT Actions schema: the public operation names, 3.0.3, the filters it must declare.
  const gpt = renderChatGptSchema(doc, filters, 'info');
  const gptOps = Object.values(gpt.paths).flatMap((item) => Object.values(item));
  const gptOp = (id) => gptOps.find((op) => op.operationId === id);
  assert('gpt: twelve operations', gptOps.length === 12);
  assert(
    'gpt: keeps the published operationIds',
    gptOp('getJobFacets') && gptOp('searchCompanies') && !gptOp('jobFacets'),
  );
  assert('gpt: OpenAPI 3.0.3, no 3.1 null type', gpt.openapi === '3.0.3' && !JSON.stringify(gpt).includes('"null"'));
  const searchParam = (name) =>
    gptOp('searchJobs')
      .parameters.map((p) => (p.$ref ? gpt.components.parameters[p.$ref.split('/').pop()] : p))
      .find((p) => p.name === name);
  assert('gpt: a closed facet carries its enum', searchParam('seniority')?.schema.items.enum?.includes('senior'));
  assert('gpt: a facet has its _exclude and _mode', searchParam('skills_exclude') && searchParam('skills_mode'));
  assert('gpt: geography has no _mode', !searchParam('countries_mode'));
  assert('gpt: a scalar filter is typed', searchParam('visa_sponsorship')?.schema.type === 'boolean');
  assert('gpt: company filters on searchCompanies', Boolean(gpt.components.parameters['company.yc_batch']));
  assert(
    'gpt: job data is typed',
    JSON.stringify(gptOp('getJob').responses['200']).includes('#/components/schemas/Job'),
  );
  assert(
    'gpt: every schema ref resolves',
    (JSON.stringify(gpt).match(/#\/components\/schemas\/[^"]+/g) ?? []).every(
      (r) => gpt.components.schemas[r.split('/').pop()],
    ),
  );
  // A 3.1 reference annotation must survive the 3.0 conversion as an allOf schema,
  // rather than becoming an ignored sibling of $ref.
  const kind = gpt.components.schemas.SuggestionPart.properties.kind;
  assert(
    'gpt: reference annotations survive the 3.0 downgrade',
    kind.description && !kind.$ref && kind.allOf?.[0].$ref === '#/components/schemas/SuggestionKind',
  );
  const long = structuredClone(doc);
  long.paths['/geo/cities'].get.description = 'x'.repeat(301);
  assert(
    'gpt: an operation description over 300 characters throws',
    throws(() => renderChatGptSchema(long, filters, '')),
  );

  let failed = 0;
  for (const c of checks) {
    if (!c.ok) failed++;
    console.log(`${c.ok ? 'PASS' : 'FAIL'}  ${c.name}`);
  }
  if (failed) {
    console.error(`\n${failed} check(s) failed`);
    process.exit(1);
  }
  console.log(`\nAll ${checks.length} checks passed.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
