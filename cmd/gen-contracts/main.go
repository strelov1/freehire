	hardconstraintBody, err := readBody(hardconstraintTS)
	if err != nil {
		return "", err
	}
	matchanalysisBody, err := readBody(matchanalysisTS)
	if err != nil {
		return "", err
	}
	resumeextractBody, err := readBody(resumeextractTS)
	if err != nil {
		return "", err
	}
	cvBody, err := readBody(cvTS)
	if err != nil {
		return "", err
	}
	cveditBody, err := readBody(cveditTS)
	if err != nil {
		return "", err
	}
	applyformBody, err := readBody(applyformTS)
	if err != nil {
		return "", err
	}
	return enrichBody + "\n" + jobviewBody + "\n" + bundleBody + "\n" + verdictBody + "\n" + atscheckBody + "\n" + cvmatchBody + "\n" + jobmatchBody + "\n" + hardconstraintBody + "\n" + matchanalysisBody + "\n" + resumeextractBody + "\n" + cvBody + "\n" + cveditBody + "\n" + applyformBody, nil
