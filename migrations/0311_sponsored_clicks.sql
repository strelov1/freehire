-- Every click on a sponsored link, valid or not, so the buyer can audit what they paid for.
-- `visitor_hash` is sha256(ip || ua || daily salt); `reason` says why a click was not valid
-- (bot, duplicate, rate, inactive, budget) and is empty for a valid one.
CREATE TABLE sponsored_clicks (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint      NOT NULL REFERENCES sponsored_campaigns (id) ON DELETE CASCADE,
    ts          timestamptz NOT NULL DEFAULT now(),
    placement   text        NOT NULL,
    visitor_hash text       NOT NULL,
    valid       boolean     NOT NULL,
    reason      text        NOT NULL DEFAULT '',
    cost_cents  bigint      NOT NULL DEFAULT 0,

    CONSTRAINT sponsored_clicks_placement_check CHECK (placement IN ('search', 'email', 'company')),
    CONSTRAINT sponsored_clicks_reason_check
        CHECK (reason IN ('', 'bot', 'duplicate', 'rate', 'inactive', 'budget')),
    CONSTRAINT sponsored_clicks_cost_check CHECK (cost_cents >= 0)
);

CREATE INDEX sponsored_clicks_visitor_idx ON sponsored_clicks (campaign_id, visitor_hash, ts);
