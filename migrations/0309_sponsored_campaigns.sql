-- A prepaid pay-per-click promotion of one open job (openspec/changes/add-sponsored-jobs-cpc).
-- Money is integer USD cents. The budget is credited by sponsored_topups (0309) and only a
-- click charge raises spent_cents, so the CHECK below is the schema-level "never overspend".
--
-- `status` lifecycle (enforced in internal/engage/sponsored, not here): draft ->
-- pending_payment -> pending_review -> active <-> paused; active -> exhausted when the budget
-- runs out (a top-up returns it to active); rejected and ended are terminal.
-- `owner_user_id` goes NULL when the owner's account is deleted: the campaign and its top-ups
-- survive so that unspent money can still be refunded by payment intent; such a campaign never
-- serves and the hourly sweep ends it.
-- `daily_cap_cents` NULL means no daily cap.
CREATE TABLE sponsored_campaigns (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id          bigint      NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    owner_user_id   bigint      REFERENCES users (id) ON DELETE SET NULL,
    status          text        NOT NULL DEFAULT 'draft',
    cpc_cents       bigint      NOT NULL,
    daily_cap_cents bigint,
    budget_cents    bigint      NOT NULL DEFAULT 0,
    spent_cents     bigint      NOT NULL DEFAULT 0,
    reviewed_by     bigint      REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at     timestamptz,
    reject_reason   text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT sponsored_campaigns_status_check
        CHECK (status IN ('draft', 'pending_payment', 'pending_review', 'active',
                          'paused', 'exhausted', 'rejected', 'ended')),
    CONSTRAINT sponsored_campaigns_cpc_check CHECK (cpc_cents >= 1),
    CONSTRAINT sponsored_campaigns_daily_cap_check
        CHECK (daily_cap_cents IS NULL OR daily_cap_cents >= 1),
    CONSTRAINT sponsored_campaigns_budget_check
        CHECK (spent_cents >= 0 AND spent_cents <= budget_cents)
);

CREATE INDEX sponsored_campaigns_status_job_idx ON sponsored_campaigns (status, job_id);
-- Referencing users needs its own index, or account deletion scans this table.
CREATE INDEX sponsored_campaigns_owner_idx ON sponsored_campaigns (owner_user_id);
CREATE INDEX sponsored_campaigns_reviewed_by_idx ON sponsored_campaigns (reviewed_by)
    WHERE reviewed_by IS NOT NULL;
