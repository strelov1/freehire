-- Two company relations a person can see and the slug rule cannot (freehire#3895).
--
-- `same`: two slugs are one employer the name fold cannot reach ("Krka, tovarna zdravil,
-- d.d., Novo mesto" beside "Krka"). Approving one writes a company_slug_aliases row with
-- reason 'moderator' (migration 0230) and moves the retiring slug's jobs, which is what
-- cmd/merge-companies does for a curated pair. The only difference is who decided.
--
-- `subsidiary`: two DIFFERENT employers, one owned by the other. Novartis Slovenija and
-- Novartis Pharma AG are separate legal entities with their own postings, and merging them
-- would put one company's jobs under another's name. They stay two companies, linked the way
-- a marketplace groups one product sold by several merchants.
--
-- Signed-in users propose and moderators decide. A wrong merge moves a public URL onto the
-- wrong employer (see docs/agents/company-identity.md), so nothing is applied on a proposal
-- alone.
--
-- Neither table has a foreign key to companies(slug), for the same reason
-- company_slug_aliases has none: companies is rebuilt from jobs, and DeleteOrphanCompanies
-- removes a row once its last posting closes. A relation a moderator decided must outlive a
-- quiet month. The readers join through companies, so a link to a company that is gone is
-- simply not shown.
--
-- New, empty tables, so plain CREATE INDEX is fine. There is nothing to scan.
CREATE TABLE IF NOT EXISTS company_relation_proposals (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         text        NOT NULL,
    -- `same`: the slug that retires. `subsidiary`: the subsidiary.
    company_slug text        NOT NULL,
    -- `same`: the slug that survives. `subsidiary`: the parent.
    target_slug  text        NOT NULL,
    note         text        NOT NULL DEFAULT '',
    proposed_by  bigint      REFERENCES users(id) ON DELETE SET NULL,
    status       text        NOT NULL DEFAULT 'pending',
    decided_by   bigint      REFERENCES users(id) ON DELETE SET NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    decided_at   timestamptz,
    CONSTRAINT company_relation_proposals_kind CHECK (kind IN ('same', 'subsidiary')),
    CONSTRAINT company_relation_proposals_status CHECK (status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT company_relation_proposals_not_self CHECK (company_slug <> target_slug),
    CONSTRAINT company_relation_proposals_note_len CHECK (char_length(note) <= 1000)
);

-- One open proposal per relation. Without it, a second person proposing the same merge
-- would add a second queue row that the moderator then decides twice.
CREATE UNIQUE INDEX IF NOT EXISTS company_relation_proposals_pending_uniq
    ON company_relation_proposals (kind, company_slug, target_slug)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS company_relation_proposals_status_idx
    ON company_relation_proposals (status, created_at);

-- Deleting an account sets these to NULL, which without an index scans the whole table.
CREATE INDEX IF NOT EXISTS company_relation_proposals_proposed_by_idx
    ON company_relation_proposals (proposed_by);
CREATE INDEX IF NOT EXISTS company_relation_proposals_decided_by_idx
    ON company_relation_proposals (decided_by);

-- One level only: a parent never has a parent of its own, and a subsidiary has exactly one
-- parent (the primary key). The approval enforces the first rule. A chain would need a
-- recursive read on every company page, and no case the issue raised needs one.
CREATE TABLE IF NOT EXISTS company_parents (
    child_slug  text        PRIMARY KEY,
    parent_slug text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT company_parents_not_self CHECK (child_slug <> parent_slug)
);

CREATE INDEX IF NOT EXISTS company_parents_parent_idx ON company_parents (parent_slug);
