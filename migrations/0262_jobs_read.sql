CREATE VIEW jobs_read AS
SELECT
    j.id,
    j.source,
    j.external_id,
    j.url,
    j.title,
    j.company,
    j.location,
    j.remote,
    j.description,
    j.posted_at,
    j.created_at,
    j.updated_at,
    j.company_slug,
    j.enrichment,
    j.enriched_at,
    j.enrichment_version,
    j.public_slug,
    j.closed_at,
    j.countries,
    j.regions,
    j.work_mode,
    j.skills,
    j.seniority,
    j.category,
    j.created_by,
    j.updated_by,
    j.posting_language,
    j.employment_type,
    j.education_level,
    j.experience_years_min,
    j.collections,
    j.content_hash,
    j.english_level,
    j.cities,
    j.view_count,
    j.applied_count,
    j.role_fingerprint,
    j.semantic_embedded_model,
    j.semantic_embedded_hash,
    j.duplicate_of,
    j.is_tech,
    j.salary_min_manual,
    j.salary_max_manual,
    j.salary_currency_manual,
    j.salary_period_manual,
    j.upvote_count,
    j.downvote_count,
    j.ats_absent_at,
    j.closed_reason,
    j.is_private,
    j.salary_min_source,
    j.salary_max_source,
    j.salary_currency_source,
    j.salary_period_source,
    j.company_slug_folded,
    j.duplicate_of_aggregator,
    j.duplicate_of_role,
    j.duplicate_of_fuzzy,
    j.requires_clearance,
    j.requirements_derived,
    j.ai_interview_reports,
    j.metros,
    j.semantic_embedded_input_hash,
    j.via_recruiter,
    j.clearance_levels,
    j.equity,
    j.perks,
    j.application_deadline,
    j.engagement,
    a.last_seen_at,
    a.hydrated_at,
    COALESCE(a.liveness_strikes, 0)::integer AS liveness_strikes
FROM jobs j
-- Keep each lookup parameterized by the posting. A flattened LEFT JOIN can
-- merge-scan activity from its first ID for every page of a keyset scan.
LEFT JOIN LATERAL (
    SELECT x.last_seen_at, x.hydrated_at, x.liveness_strikes
    FROM job_activity x WHERE x.job_id = j.id
    LIMIT 1
) a ON true;
