-- One Stripe Checkout payment that funded a sponsored campaign. `stripe_session_id` UNIQUE is
-- what makes a redelivered webhook credit the budget once. `payment_intent_id` is kept for the
-- refund of a rejected campaign.
CREATE TABLE sponsored_topups (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id       bigint      NOT NULL REFERENCES sponsored_campaigns (id) ON DELETE CASCADE,
    stripe_session_id text        NOT NULL UNIQUE,
    payment_intent_id text,
    amount_cents      bigint      NOT NULL CHECK (amount_cents > 0),
    refunded_at       timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX sponsored_topups_campaign_idx ON sponsored_topups (campaign_id);
